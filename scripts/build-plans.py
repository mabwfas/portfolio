"""Build the Plans section of index.html from scripts/plans.json.

Usage (from the repo root):  python scripts/build-plans.py

Replaces everything between <!-- PLANS:START --> and <!-- PLANS:END -->.
Prices are deliberately absent: every plan asks for a quote (#quote form).
"""
import html
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from sections import renumber  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "scripts" / "plans.json").read_text(encoding="utf-8"))
INDEX = ROOT / "index.html"

e = html.escape


def icon(name, cls="ico"):
    return f'<svg class="{cls}"><use href="#i-{name}" /></svg>'


def quote_link(cat, plan, cls, short=None):
    # short: a second, shorter label the table header uses on phones.
    label = ('<span class="lbl-full">Get Pricing</span><span class="lbl-short">' + e(short) + '</span>') if short else "Get Pricing"
    return (f'<a class="btn {cls}" href="#quote" data-quote-type="{e(cat["label"].replace(" Software", " software"))}" '
            f'data-quote-plan="{e(plan["name"])}">{label}{icon("arrow-right")}</a>')


def card(cat, plan):
    featured = plan.get("popular")
    out = [f'<article class="tier{" tier-featured" if featured else ""} reveal">']
    if featured:
        out.append('<p class="tier-badge">Most Popular</p>')
    out.append(f'<p class="tier-icon">{icon(plan["icon"])}</p>')
    out.append(f'<h4 class="tier-name">{e(plan["name"])}</h4>')
    out.append(f'<p class="tier-price">Price on request</p>')
    out.append(f'<p class="tier-desc">{e(plan["desc"])}</p>')
    out.append('<ul class="tier-list">' + "".join(f"<li>{icon('check')}{e(h)}</li>" for h in plan["highlights"]) + "</ul>")
    out.append(f'<p class="tier-foot">{icon("target")}{e(plan["foot"])}</p>')
    out.append(quote_link(cat, plan, "btn-accent btn-block" if featured else "btn-ghost btn-block"))
    out.append("</article>")
    return "\n".join(out)


def cell(value, popular):
    cls = ' class="is-popular"' if popular else ""
    if value is True:
        return f'<td{cls}>{icon("check", "ico yes")}<span class="visually-hidden">Included</span></td>'
    if value is False:
        return f'<td{cls}><span class="dash" aria-hidden="true"></span><span class="visually-hidden">Not included</span></td>'
    return f'<td{cls}><span class="val">{e(str(value))}</span></td>'


def table(cat):
    plans = cat["plans"]
    head = ['<th scope="col" class="compare-corner">Features</th>']
    for p in plans:
        pop = " is-popular" if p.get("popular") else ""
        head.append(
            f'<th scope="col" class="compare-plan{pop}">'
            f'<span class="cp-full">{e(p["name"])}</span><span class="cp-short">{e(p["short"])}</span>'
            f'<span class="cp-foot">{e(p["foot"])}</span>'
            f'{quote_link(cat, p, "btn-xs " + ("btn-accent" if p.get("popular") else "btn-primary"), "Quote")}</th>')
    rows = []
    for g in cat["groups"]:
        rows.append(f'<tr class="compare-group"><th scope="colgroup" colspan="{len(plans) + 1}">{e(g["name"])}</th></tr>')
        for r in g["rows"]:
            label, values = r[0], r[1:]
            assert len(values) == len(plans), (cat["id"], label)
            rows.append(f'<tr><th scope="row">{e(label)}</th>'
                        + "".join(cell(v, plans[i].get("popular")) for i, v in enumerate(values)) + "</tr>")
    return (f'<table class="compare">\n<caption class="visually-hidden">{e(cat["title"])} compared feature by feature</caption>\n'
            f'<thead><tr>{"".join(head)}</tr></thead>\n<tbody>\n' + "\n".join(rows) + "\n</tbody>\n</table>")


def panel(cat, first):
    hidden = "" if first else " hidden"
    return f"""<div class="plan-panel" role="tabpanel" id="panel-{cat['id']}" aria-labelledby="tab-{cat['id']}" data-type="{e(cat['label'])}"{hidden}>
<header class="panel-head">
<p class="eyebrow print-only"><span class="num">14</span>Plans</p>
<h3 class="panel-title">{e(cat['title'])}</h3>
<p class="panel-note">{icon('message')}Pricing on request. Pick a plan and we'll send you a tailored quote.</p>
</header>
<div class="tiers">
{chr(10).join(card(cat, p) for p in cat['plans'])}
</div>
<div class="compare-head">
<h4 class="compare-title">Compare every {e(cat['label'])} feature</h4>
<a class="text-link" href="#quote">Not sure which plan fits? Ask us{icon('arrow-right')}</a>
</div>
{table(cat)}
</div>"""


cats = DATA["categories"]
NOT_FIRST = ' tabindex="-1"'
tabs = "\n".join(
    f'<button class="plan-tab" role="tab" id="tab-{c["id"]}" aria-controls="panel-{c["id"]}" '
    f'aria-selected="{"true" if i == 0 else "false"}"{"" if i == 0 else NOT_FIRST}>{e(c["label"])}</button>'
    for i, c in enumerate(cats))

section = f"""<!-- PLANS:START (generated by scripts/build-plans.py from scripts/plans.json; edit the JSON, not this block) -->
        <section class="page tone-sand plans" id="plans" data-slide="14" data-label="Plans">
            <div class="wrap">
                <header class="sec-head sec-head-wide reveal">
                    <p class="eyebrow"><span class="num">14</span>Plans</p>
                    <h2 class="h2">Build a Brand That Can <em>Scale to Millions</em></h2>
                    <p class="lede">You're not here to "get a website built." You're here because you want a real brand,
                        one that looks powerful, converts consistently, and can scale with ads, content, and traffic
                        without breaking.</p>
                </header>
                <div class="plan-tabs reveal" role="tablist" aria-label="Plan type">
{tabs}
                </div>
{chr(10).join(panel(c, i == 0) for i, c in enumerate(cats))}
            </div>
        </section>
        <!-- PLANS:END -->"""

src = INDEX.read_text(encoding="utf-8")
new, n = re.subn(r"<!-- PLANS:START.*?<!-- PLANS:END -->", lambda m: section, src, flags=re.S)
if n != 1:
    raise SystemExit("PLANS markers not found exactly once in index.html")
new, _ = renumber(new)  # plan numbers follow the section's position
INDEX.write_text(new, encoding="utf-8")
rows = sum(len(g["rows"]) for c in cats for g in c["groups"])
print(f"Plans section rebuilt: {len(cats)} categories, {sum(len(c['plans']) for c in cats)} plans, {rows} comparison rows")
